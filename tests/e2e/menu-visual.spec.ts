import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { expect, test } from '@playwright/test';
import { format } from 'prettier';

type Locale = 'vi' | 'en' | 'ko';
type Viewport = Readonly<{ height: number; name: string; width: number }>;
type MenuVisualMetrics = Readonly<{
  categoryCount: number;
  chapterPatternCount: number;
  desktopHeaderMapsVisible: boolean;
  documentScrollWidth: number;
  mobileBarClearance: number | null;
  mobileBarVisible: boolean;
  imageCount: number;
  itemCount: number;
  loadedImageCount: number;
  locale: Locale;
  navigationPosition: string;
  navigationTop: number;
  picksVisible: boolean;
  screenshotBytes: number;
  textOverflowCount: number;
  viewport: Viewport;
}>;

const locales: readonly Locale[] = ['vi', 'en', 'ko'];
const viewports: readonly Viewport[] = [
  { height: 900, name: 'desktop-1440x900', width: 1440 },
  { height: 1024, name: 'tablet-768x1024', width: 768 },
  { height: 844, name: 'mobile-390x844', width: 390 },
];
const outputDirectory = join(process.cwd(), 'artifacts', 'visual-qa', 'menu');
const metrics: MenuVisualMetrics[] = [];

function formatComparison(values: readonly MenuVisualMetrics[]): string {
  const rows = values
    .map(
      (value) =>
        `| ${value.locale} | ${value.viewport.name} | ${value.categoryCount} | ${value.chapterPatternCount} | ${value.itemCount} | ${value.imageCount}/${value.loadedImageCount} | ${value.picksVisible ? 'visible' : 'hidden'} | ${value.navigationPosition} | ${value.navigationTop}px | ${value.textOverflowCount} | ${value.documentScrollWidth}px | ${value.screenshotBytes} |`,
    )
    .join('\n');

  return `# Menu Visual QA: New Stitch Baseline

Generated by \`pnpm exec playwright test tests/e2e/menu-visual.spec.ts --workers=1\`.

The page follows the tracked \`Menu — NAVIDO (Desktop)\` and \`Menu — NAVIDO (Mobile)\` composition while retaining all 130 normalized source rows. Desktop and tablet expose the full editorial introduction, four source-backed picks, sticky index, and nine media placements. Mobile follows the compact reference sequence with three visible media placements and a sticky horizontal category rail.

The retained reference screenshots, HTML exports, dimensions, and Stitch screen IDs are indexed in \`artifacts/stitch-references/menu/README.md\`. The shared site shell remains unchanged by product decision, and the complete source menu extends the shorter illustrative reference content.

| Locale | Viewport | Categories | Patterns | Rows | Images loaded | Picks | Nav position | Nav top | Text overflow | Document width | Screenshot bytes |
| --- | --- | ---: | ---: | ---: | --- | --- | --- | ---: | ---: | ---: | ---: |
${rows}

The verifier asserts source completeness, responsive editorial media, chapter pattern coverage, sticky navigation, decoded images, price/name containment, and zero document overflow. The shared site shell remains intentionally unchanged.
`;
}

test.afterAll(async () => {
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(
    join(outputDirectory, 'metrics.json'),
    await format(`${JSON.stringify(metrics, null, 2)}\n`, {
      filepath: 'metrics.json',
    }),
  );
  await writeFile(
    join(outputDirectory, 'comparison.md'),
    await format(formatComparison(metrics), { filepath: 'comparison.md' }),
  );
});

for (const locale of locales) {
  for (const viewport of viewports) {
    test(`verifies ${locale} Menu at ${viewport.name}`, async ({ page }) => {
      await page.setViewportSize(viewport);
      const response = await page.goto(`/${locale}/menu`, {
        waitUntil: 'networkidle',
      });

      expect(response?.status()).toBe(200);
      await expect(page.locator('[data-menu-category]')).toHaveCount(14);
      await expect(page.locator('[data-menu-item]')).toHaveCount(130);

      const expectedImageCount = viewport.width >= 768 ? 9 : 3;
      const images = page.locator('main img:visible');
      await expect(images).toHaveCount(expectedImageCount);
      for (let index = 0; index < expectedImageCount; index += 1) {
        const image = images.nth(index);
        await image.scrollIntoViewIfNeeded();
        await expect
          .poll(() =>
            image.evaluate((element) => {
              const htmlImage = element as HTMLImageElement;
              return htmlImage.complete && htmlImage.naturalWidth > 0;
            }),
          )
          .toBe(true);
      }

      await page.evaluate(() =>
        window.scrollTo({ top: 480, behavior: 'instant' }),
      );
      const metricsForViewport = await page.evaluate(() => {
        const mobileNavigation = document
          .querySelector<HTMLElement>('[data-menu-mobile-category-nav]')
          ?.closest<HTMLElement>('.sticky');
        const desktopNavigation = document
          .querySelector<HTMLElement>('[data-menu-desktop-category-nav]')
          ?.closest<HTMLElement>('.sticky');
        const navigation =
          window.innerWidth >= 768 ? desktopNavigation : mobileNavigation;
        const itemNames = Array.from(
          document.querySelectorAll<HTMLElement>('[data-menu-item-name]'),
        );

        const headerMaps = document
          .querySelector('header nav')
          ?.parentElement?.querySelector<HTMLAnchorElement>(
            'a[href*="google.com/maps/search"]',
          );
        const mobileBar = document.querySelector<HTMLElement>(
          '[data-testid="mobile-conversion-bar"]',
        );
        const footerLinks =
          document.querySelectorAll<HTMLAnchorElement>('footer a');
        const finalFooterLink = footerLinks.item(footerLinks.length - 1);
        const shell = {
          desktopHeaderMapsVisible: Boolean(
            headerMaps && headerMaps.getClientRects().length > 0,
          ),
          mobileBarClearance:
            mobileBar && finalFooterLink
              ? Math.floor(
                  mobileBar.getBoundingClientRect().top -
                    (finalFooterLink.getBoundingClientRect().bottom -
                      Math.max(
                        0,
                        document.documentElement.scrollHeight -
                          window.innerHeight,
                      )),
                )
              : null,
          mobileBarVisible: Boolean(
            mobileBar && mobileBar.getClientRects().length > 0,
          ),
        };

        return {
          ...shell,
          categoryCount: document.querySelectorAll('[data-menu-category]')
            .length,
          chapterPatternCount: new Set(
            Array.from(
              document.querySelectorAll<HTMLElement>('[data-menu-chapter]'),
            ).map((chapter) => chapter.dataset.menuChapter),
          ).size,
          documentScrollWidth: document.documentElement.scrollWidth,
          imageCount: Array.from(
            document.querySelectorAll<HTMLImageElement>('main img'),
          ).filter((image) => image.getClientRects().length > 0).length,
          itemCount: document.querySelectorAll('[data-menu-item]').length,
          loadedImageCount: Array.from(
            document.querySelectorAll<HTMLImageElement>('main img'),
          ).filter(
            (image) =>
              image.getClientRects().length > 0 &&
              image.complete &&
              image.naturalWidth > 0,
          ).length,
          navigationPosition: navigation
            ? getComputedStyle(navigation).position
            : '',
          navigationTop: Math.round(
            navigation?.getBoundingClientRect().top ?? -1,
          ),
          picksVisible:
            (document
              .querySelector<HTMLElement>('[data-menu-picks]')
              ?.getClientRects().length ?? 0) > 0,
          textOverflowCount: itemNames.filter(
            (node) => node.scrollWidth > node.clientWidth + 1,
          ).length,
        };
      });

      expect(metricsForViewport.chapterPatternCount).toBe(8);
      expect(metricsForViewport.imageCount).toBe(expectedImageCount);
      expect(metricsForViewport.loadedImageCount).toBe(expectedImageCount);
      expect(metricsForViewport.picksVisible).toBe(viewport.width >= 768);
      expect(metricsForViewport.navigationPosition).toBe('sticky');
      expect(metricsForViewport.navigationTop).toBeGreaterThanOrEqual(0);
      expect(metricsForViewport.textOverflowCount).toBe(0);
      expect(metricsForViewport.documentScrollWidth).toBeLessThanOrEqual(
        viewport.width,
      );
      expect(metricsForViewport.desktopHeaderMapsVisible).toBe(
        viewport.width >= 768,
      );
      expect(metricsForViewport.mobileBarVisible).toBe(viewport.width < 768);
      if (viewport.width < 768) {
        expect(metricsForViewport.mobileBarClearance).toBeGreaterThanOrEqual(0);
      } else {
        expect(metricsForViewport.mobileBarClearance).toBeNull();
      }

      const screenshot = await page.screenshot({
        fullPage: true,
        path: join(outputDirectory, `${locale}-${viewport.name}.png`),
      });
      expect(screenshot.byteLength).toBeGreaterThan(30_000);

      metrics.push({
        ...metricsForViewport,
        locale,
        screenshotBytes: screenshot.byteLength,
        viewport,
      });
    });
  }
}
