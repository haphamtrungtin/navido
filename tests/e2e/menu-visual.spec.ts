import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { expect, test } from '@playwright/test';
import { format } from 'prettier';

type Locale = 'vi' | 'en' | 'ko';
type Viewport = Readonly<{ height: number; name: string; width: number }>;
type MenuVisualMetrics = Readonly<{
  categoryCount: number;
  documentScrollWidth: number;
  imageCount: number;
  itemCount: number;
  loadedImageCount: number;
  locale: Locale;
  navigationPosition: string;
  navigationTop: number;
  screenshotBytes: number;
  textOverflowCount: number;
  viewport: Viewport;
}>;

const locales: readonly Locale[] = ['vi', 'en', 'ko'];
const viewports: readonly Viewport[] = [
  { height: 900, name: 'desktop-1440x900', width: 1440 },
  { height: 1024, name: 'tablet-768x1024', width: 768 },
  { height: 844, name: 'mobile-390x844', width: 390 },
];
const outputDirectory = join(process.cwd(), 'artifacts', 'visual-qa', 'menu');
const metrics: MenuVisualMetrics[] = [];

function formatComparison(values: readonly MenuVisualMetrics[]): string {
  const rows = values
    .map(
      (value) =>
        `| ${value.locale} | ${value.viewport.name} | ${value.categoryCount} | ${value.itemCount} | ${value.imageCount}/${value.loadedImageCount} | ${value.navigationPosition} | ${value.navigationTop}px | ${value.textOverflowCount} | ${value.documentScrollWidth}px | ${value.screenshotBytes} |`,
    )
    .join('\n');

  return `# Menu Visual QA

Generated by \`pnpm exec playwright test tests/e2e/menu-visual.spec.ts --workers=1\`.

The full normalized data set extends Stitch's illustrative sample-row system: all 130 source rows are rendered in the same restrained row treatment, with the two approved Stitch images retained as visual breaks.

| Locale | Viewport | Categories | Rows | Images loaded | Nav position | Nav top | Text overflow | Document width | Screenshot bytes |
| --- | --- | ---: | ---: | --- | --- | ---: | ---: | ---: | ---: |
${rows}

The verifier asserts the header/category navigation remains sticky, prices and labels retain their grid containment, image breaks decode, and intentional horizontal category navigation does not produce document overflow.
`;
}

test.afterAll(async () => {
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(
    join(outputDirectory, 'metrics.json'),
    await format(`${JSON.stringify(metrics, null, 2)}\n`, {
      filepath: 'metrics.json',
    }),
  );
  await writeFile(
    join(outputDirectory, 'comparison.md'),
    await format(formatComparison(metrics), { filepath: 'comparison.md' }),
  );
});

for (const locale of locales) {
  for (const viewport of viewports) {
    test(`verifies ${locale} Menu at ${viewport.name}`, async ({ page }) => {
      await page.setViewportSize(viewport);
      const response = await page.goto(`/${locale}/menu`, {
        waitUntil: 'networkidle',
      });

      expect(response?.status()).toBe(200);
      await expect(page.locator('[data-menu-category]')).toHaveCount(14);
      await expect(page.locator('[data-menu-item]')).toHaveCount(130);

      const images = page.locator('main img');
      await expect(images).toHaveCount(2);
      for (let index = 0; index < 2; index += 1) {
        const image = images.nth(index);
        await image.scrollIntoViewIfNeeded();
        await expect
          .poll(() =>
            image.evaluate((element) => {
              const htmlImage = element as HTMLImageElement;
              return htmlImage.complete && htmlImage.naturalWidth > 0;
            }),
          )
          .toBe(true);
      }

      await page.evaluate(() =>
        window.scrollTo({ top: 480, behavior: 'instant' }),
      );
      const metricsForViewport = await page.evaluate(() => {
        const mobileNavigation =
          document.querySelector<HTMLElement>('main > div.sticky');
        const desktopNavigation = document.querySelector<HTMLElement>(
          'main aside > div.sticky',
        );
        const navigation =
          window.innerWidth >= 768 ? desktopNavigation : mobileNavigation;
        const itemNames = Array.from(
          document.querySelectorAll<HTMLElement>('[data-menu-item-name]'),
        );

        return {
          categoryCount: document.querySelectorAll('[data-menu-category]')
            .length,
          documentScrollWidth: document.documentElement.scrollWidth,
          imageCount: document.querySelectorAll('main img').length,
          itemCount: document.querySelectorAll('[data-menu-item]').length,
          loadedImageCount: Array.from(
            document.querySelectorAll('main img'),
          ).filter(
            (image) =>
              (image as HTMLImageElement).complete &&
              (image as HTMLImageElement).naturalWidth > 0,
          ).length,
          navigationPosition: navigation
            ? getComputedStyle(navigation).position
            : '',
          navigationTop: Math.round(
            navigation?.getBoundingClientRect().top ?? -1,
          ),
          textOverflowCount: itemNames.filter(
            (node) => node.scrollWidth > node.clientWidth + 1,
          ).length,
        };
      });

      expect(metricsForViewport.imageCount).toBe(2);
      expect(metricsForViewport.loadedImageCount).toBe(2);
      expect(metricsForViewport.navigationPosition).toBe('sticky');
      expect(metricsForViewport.navigationTop).toBeGreaterThanOrEqual(0);
      expect(metricsForViewport.textOverflowCount).toBe(0);
      expect(metricsForViewport.documentScrollWidth).toBeLessThanOrEqual(
        viewport.width,
      );

      const screenshot = await page.screenshot({
        fullPage: true,
        path: join(outputDirectory, `${locale}-${viewport.name}.png`),
      });
      expect(screenshot.byteLength).toBeGreaterThan(30_000);

      metrics.push({
        ...metricsForViewport,
        locale,
        screenshotBytes: screenshot.byteLength,
        viewport,
      });
    });
  }
}
