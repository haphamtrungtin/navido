import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { expect, test } from '@playwright/test';
import { format } from 'prettier';

type Locale = 'vi' | 'en' | 'ko';
type Viewport = Readonly<{ height: number; name: string; width: number }>;
type HomeVisualMetrics = Readonly<{
  contentPaddingTop: number[];
  desktopHeaderMapsVisible: boolean;
  documentScrollWidth: number;
  mobileBarClearance: number | null;
  mobileBarVisible: boolean;
  gridTracks: Record<'highlights' | 'introduction' | 'location', number>;
  heroBackground: string;
  heroBackgroundPosition: string;
  heroBackgroundSize: string;
  heroHeight: number;
  highlightCount: number;
  imageCount: number;
  loadedImageCount: number;
  locale: Locale;
  locationCount: number;
  screenshotBytes: number;
  sectionOrder: string[];
  sectionScrollWidths: number[];
  textOverflowCount: number;
  viewport: Viewport;
}>;

const locales: readonly Locale[] = ['vi', 'en', 'ko'];
const viewports: readonly Viewport[] = [
  { height: 900, name: 'desktop-1440x900', width: 1440 },
  { height: 1024, name: 'tablet-768x1024', width: 768 },
  { height: 844, name: 'mobile-390x844', width: 390 },
];
const expectedGridTracks = {
  'desktop-1440x900': { highlights: 3, introduction: 12, location: 12 },
  'mobile-390x844': { highlights: 1, introduction: 1, location: 1 },
  'tablet-768x1024': { highlights: 3, introduction: 1, location: 1 },
} as const;
const sectionOrder = [
  'hero',
  'introduction',
  'signature-highlights',
  'location-invitation',
] as const;
const outputDirectory = join(process.cwd(), 'artifacts', 'visual-qa', 'home');
const collectedMetrics: HomeVisualMetrics[] = [];

function formatMetrics(metrics: readonly HomeVisualMetrics[]): string {
  const rows = [...metrics]
    .sort(
      (left, right) =>
        left.locale.localeCompare(right.locale) ||
        viewports.findIndex(
          (viewport) => viewport.name === left.viewport.name,
        ) -
          viewports.findIndex(
            (viewport) => viewport.name === right.viewport.name,
          ),
    )
    .map(
      (metric) =>
        `| ${metric.locale} | ${metric.viewport.name} | ${metric.heroHeight}px | ${metric.gridTracks.introduction}/${metric.gridTracks.highlights}/${metric.gridTracks.location} | ${metric.contentPaddingTop.join('/')}px | ${metric.highlightCount} | ${metric.locationCount} | ${metric.imageCount}/${metric.loadedImageCount} | ${metric.textOverflowCount} | ${metric.documentScrollWidth} | ${metric.screenshotBytes} |`,
    );

  return `# Home Visual QA

Generated by \`pnpm verify:home-visual\`. This verifier reruns all three locales at the required desktop, derived tablet, and mobile viewports, refreshes the PNG captures, and writes these actual measurements.

## Stitch-Derived Contracts

| Contract | Expected assertion |
| --- | --- |
| Hierarchy | hero, introduction, signature highlights, location invitation |
| Hero crop | approved interior image with \`background-size: cover\` and centered position |
| Editorial grid | introduction/location: 12 tracks desktop, one track tablet/mobile; highlights: three tracks desktop/tablet, one mobile |
| Vertical rhythm | content sections have at least 110px top padding on desktop/tablet and 70px on mobile |
| Highlights and visit | three highlight articles and one location invitation |
| Text and containment | no measured heading/body overflow; document and every section fit its viewport |

## Actual Measurements

| Locale | Viewport | Hero height | Intro/Highlights/Location tracks | Content top padding | Highlights | Location | Images decoded | Text overflow nodes | Document width | Screenshot bytes |
| --- | --- | ---: | --- | --- | ---: | ---: | --- | ---: | ---: | ---: |
${rows.join('\n')}

## Discrepancy Log

No discrepancy was detected in the ${metrics.length} generated runs. Any future contract failure stops \`pnpm verify:home-visual\` and leaves the failing viewport in the Playwright report. The approved temporary Stitch imagery remains listed in \`docs/missing-content.md\`.
`;
}

test.afterAll(async () => {
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(
    join(outputDirectory, 'metrics.json'),
    await format(`${JSON.stringify(collectedMetrics, null, 2)}\n`, {
      filepath: 'metrics.json',
    }),
  );
  await writeFile(
    join(outputDirectory, 'comparison.md'),
    await format(formatMetrics(collectedMetrics), {
      filepath: 'comparison.md',
    }),
  );
});

for (const locale of locales) {
  for (const viewport of viewports) {
    test(`verifies ${locale} Home at ${viewport.name}`, async ({ page }) => {
      await page.setViewportSize(viewport);
      const response = await page.goto(`/${locale}`, {
        waitUntil: 'networkidle',
      });

      expect(response?.status()).toBe(200);
      await expect(
        page.getByRole('heading', { level: 1, name: 'NAVIDO' }),
      ).toBeInViewport();

      const images = page.locator('main img');
      await expect(images).toHaveCount(6);
      for (let index = 0; index < 6; index += 1) {
        const image = images.nth(index);
        await image.scrollIntoViewIfNeeded();
        await expect
          .poll(() =>
            image.evaluate((element) => {
              const htmlImage = element as HTMLImageElement;
              return htmlImage.complete && htmlImage.naturalWidth > 0;
            }),
          )
          .toBe(true);
      }
      await page.evaluate(() =>
        window.scrollTo({ top: 0, behavior: 'instant' }),
      );

      const metrics = await page.evaluate(() => {
        const main = document.querySelector('main');
        const sections = Array.from(
          main?.querySelectorAll(':scope > [data-home-section]') ?? [],
        );
        const hero = sections[0];
        const heroImage = hero?.querySelector<HTMLElement>(
          '[data-home-hero-image]',
        );
        const heroStyle = heroImage ? getComputedStyle(heroImage) : null;
        const getTrackCount = (name: string) => {
          const grid = main?.querySelector<HTMLElement>(
            `[data-home-grid="${name}"]`,
          );
          const template = grid
            ? getComputedStyle(grid).gridTemplateColumns
            : '';
          return template && template !== 'none'
            ? template.trim().split(/\s+/).length
            : 0;
        };
        const textNodes = Array.from(
          main?.querySelectorAll<HTMLElement>('h1, h2, h3, p') ?? [],
        );
        const images = Array.from(document.images);

        const headerMaps = document
          .querySelector('header nav')
          ?.parentElement?.querySelector<HTMLAnchorElement>(
            'a[href*="google.com/maps/search"]',
          );
        const mobileBar = document.querySelector<HTMLElement>(
          '[data-testid="mobile-conversion-bar"]',
        );
        const footerLinks =
          document.querySelectorAll<HTMLAnchorElement>('footer a');
        const finalFooterLink = footerLinks.item(footerLinks.length - 1);
        const shell = {
          desktopHeaderMapsVisible: Boolean(
            headerMaps && headerMaps.getClientRects().length > 0,
          ),
          mobileBarClearance:
            mobileBar && finalFooterLink
              ? Math.floor(
                  mobileBar.getBoundingClientRect().top -
                    (finalFooterLink.getBoundingClientRect().bottom -
                      Math.max(
                        0,
                        document.documentElement.scrollHeight -
                          window.innerHeight,
                      )),
                )
              : null,
          mobileBarVisible: Boolean(
            mobileBar && mobileBar.getClientRects().length > 0,
          ),
        };

        return {
          ...shell,
          contentPaddingTop: sections
            .slice(1)
            .map((section) =>
              Math.round(parseFloat(getComputedStyle(section).paddingTop)),
            ),
          documentScrollWidth: document.documentElement.scrollWidth,
          gridTracks: {
            highlights: getTrackCount('highlights'),
            introduction: getTrackCount('introduction'),
            location: getTrackCount('location'),
          },
          heroBackground: heroStyle?.backgroundImage ?? '',
          heroBackgroundPosition: heroStyle?.backgroundPosition ?? '',
          heroBackgroundSize: heroStyle?.backgroundSize ?? '',
          heroHeight: Math.round(hero?.getBoundingClientRect().height ?? 0),
          highlightCount:
            main?.querySelectorAll('[data-home-highlight]').length ?? 0,
          imageCount: images.length,
          loadedImageCount: images.filter(
            (image) => image.complete && image.naturalWidth > 0,
          ).length,
          locationCount:
            main?.querySelectorAll('[data-home-section="location-invitation"]')
              .length ?? 0,
          sectionOrder: sections.map(
            (section) => section.getAttribute('data-home-section') ?? '',
          ),
          sectionScrollWidths: sections.map((section) => section.scrollWidth),
          textOverflowCount: textNodes.filter(
            (node) => node.scrollWidth > node.clientWidth,
          ).length,
        };
      });

      expect(metrics.sectionOrder).toEqual(sectionOrder);
      expect(metrics.heroBackground).toContain('home-cafe-interior.jpg');
      expect(metrics.heroBackgroundSize).toBe('cover');
      expect(metrics.heroBackgroundPosition).toBe('50% 50%');
      expect(metrics.heroHeight).toBeGreaterThanOrEqual(viewport.height - 84);
      expect(metrics.gridTracks).toEqual(
        expectedGridTracks[viewport.name as keyof typeof expectedGridTracks],
      );
      expect(
        metrics.contentPaddingTop.every(
          (padding) => padding >= (viewport.width < 768 ? 70 : 110),
        ),
      ).toBe(true);
      expect(metrics.highlightCount).toBe(3);
      expect(metrics.locationCount).toBe(1);
      expect(metrics.imageCount).toBe(6);
      expect(metrics.loadedImageCount).toBe(6);
      expect(metrics.textOverflowCount).toBe(0);
      expect(metrics.documentScrollWidth).toBeLessThanOrEqual(viewport.width);
      expect(metrics.desktopHeaderMapsVisible).toBe(viewport.width >= 768);
      expect(metrics.mobileBarVisible).toBe(viewport.width < 768);
      if (viewport.width < 768) {
        expect(metrics.mobileBarClearance).toBeGreaterThanOrEqual(0);
      } else {
        expect(metrics.mobileBarClearance).toBeNull();
      }
      expect(
        metrics.sectionScrollWidths.every((width) => width <= viewport.width),
      ).toBe(true);

      const screenshot = await page.screenshot({
        path: join(outputDirectory, `${locale}-${viewport.name}.png`),
      });
      expect(screenshot.byteLength).toBeGreaterThan(30_000);

      collectedMetrics.push({
        ...metrics,
        locale,
        screenshotBytes: screenshot.byteLength,
        viewport,
      });
    });
  }
}
