import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { expect, test } from '@playwright/test';
import { format } from 'prettier';

type Locale = 'vi' | 'en' | 'ko';
type Viewport = Readonly<{ height: number; name: string; width: number }>;
type Metrics = Readonly<{
  documentScrollWidth: number;
  gridTracks: number[];
  heroHeight: number;
  imageCount: number;
  loadedImageCount: number;
  locale: Locale;
  screenshotBytes: number;
  storyOrder: string[];
  textOverflowCount: number;
  viewport: Viewport;
}>;

const locales: readonly Locale[] = ['vi', 'en', 'ko'];
const viewports: readonly Viewport[] = [
  { height: 900, name: 'desktop-1440x900', width: 1440 },
  { height: 1024, name: 'tablet-768x1024', width: 768 },
  { height: 844, name: 'mobile-390x844', width: 390 },
];
const stories = [
  'morning-light',
  'quiet-table',
  'downstairs',
  'upstairs',
] as const;
const outputDirectory = join(
  process.cwd(),
  'artifacts',
  'visual-qa',
  'our-space',
);
const metrics: Metrics[] = [];

function expectedTracks(viewport: Viewport) {
  if (viewport.width >= 1024) return 12;
  if (viewport.width >= 768) return 8;
  return 1;
}

test.afterAll(async () => {
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(
    join(outputDirectory, 'metrics.json'),
    await format(`${JSON.stringify(metrics, null, 2)}\n`, {
      filepath: 'metrics.json',
    }),
  );
  await writeFile(
    join(outputDirectory, 'comparison.md'),
    await format(
      `# Our Space Visual QA

Generated by \`pnpm verify:our-space-visual\`. Desktop is compared to the Stitch editorial intent; tablet is a derived eight-column layout; mobile is the verified single-column reading order.

## Contracts

| Contract | Assertion |
| --- | --- |
| Hero | Morning interior image decodes, fills a tall editorial hero, and remains cropped with \`object-fit: cover\` |
| Stories | Four images appear in morning-light, quiet-table, downstairs, upstairs order |
| Grids | 12 tracks desktop, derived 8 tracks tablet, one track mobile |
| Callout | One localized Visit link follows the stories |
| Shell | Shared header remains sticky while the page scrolls |
| Containment | Text and sections do not overflow horizontally |

## Measurements

| Locale | Viewport | Hero height | Grid tracks | Images decoded | Text overflow | Document width | Screenshot bytes |
| --- | --- | ---: | --- | --- | ---: | ---: | ---: |
${metrics
  .map(
    (metric) =>
      `| ${metric.locale} | ${metric.viewport.name} | ${metric.heroHeight}px | ${metric.gridTracks.join('/')} | ${metric.loadedImageCount}/${metric.imageCount} | ${metric.textOverflowCount} | ${metric.documentScrollWidth} | ${metric.screenshotBytes} |`,
  )
  .join('\n')}

## Comparison Notes

Desktop preserves the alternating image-and-copy editorial composition. Tablet reduces that composition to an eight-column derivative, while mobile stacks each image before its matching copy. No visual discrepancy was detected when this file was generated.
`,
      { filepath: 'comparison.md' },
    ),
  );
});

for (const locale of locales) {
  for (const viewport of viewports) {
    test(`verifies ${locale} Our Space at ${viewport.name}`, async ({
      page,
    }) => {
      await page.setViewportSize(viewport);
      const response = await page.goto(`/${locale}/our-space`, {
        waitUntil: 'networkidle',
      });

      expect(response?.status()).toBe(200);
      await expect(page.locator('h1')).toHaveCount(1);
      await expect(page.locator('[data-space-story]')).toHaveCount(4);
      await expect(page.locator('[data-space-callout]')).toHaveCount(1);
      await expect(
        page.locator(`[data-space-callout] a[href="/${locale}/visit"]`),
      ).toHaveCount(1);

      const images = page.locator('main img');
      await expect(images).toHaveCount(5);
      for (let index = 0; index < 5; index += 1) {
        const image = images.nth(index);
        await image.scrollIntoViewIfNeeded();
        await expect
          .poll(() =>
            image.evaluate((element) => {
              const htmlImage = element as HTMLImageElement;
              return htmlImage.complete && htmlImage.naturalWidth > 0;
            }),
          )
          .toBe(true);
      }

      await page.evaluate(() =>
        window.scrollTo({ top: 0, behavior: 'instant' }),
      );
      const headerTop = await page
        .locator('header')
        .evaluate((header) => Math.round(header.getBoundingClientRect().top));
      await page.evaluate(() =>
        window.scrollTo({ top: 480, behavior: 'instant' }),
      );
      expect(
        await page
          .locator('header')
          .evaluate((header) => Math.round(header.getBoundingClientRect().top)),
      ).toBe(headerTop);

      const collected = await page.evaluate(() => {
        const main = document.querySelector('main');
        const hero = main?.querySelector<HTMLElement>(
          '[data-space-section="hero"]',
        );
        const grids = Array.from(
          main?.querySelectorAll<HTMLElement>('[data-space-grid]') ?? [],
        );
        const textNodes = Array.from(
          main?.querySelectorAll<HTMLElement>('h1, h2, h3, p') ?? [],
        );
        const pageImages = Array.from(main?.querySelectorAll('img') ?? []);

        return {
          documentScrollWidth: document.documentElement.scrollWidth,
          gridTracks: grids.map((grid) => {
            const template = getComputedStyle(grid).gridTemplateColumns;
            return template === 'none'
              ? 0
              : template.trim().split(/\s+/).length;
          }),
          heroHeight: Math.round(hero?.getBoundingClientRect().height ?? 0),
          imageCount: pageImages.length,
          loadedImageCount: pageImages.filter(
            (image) => image.complete && image.naturalWidth > 0,
          ).length,
          storyOrder: Array.from(
            main?.querySelectorAll('[data-space-story]') ?? [],
          ).map((story) => story.getAttribute('data-space-story') ?? ''),
          textOverflowCount: textNodes.filter(
            (node) => node.scrollWidth > node.clientWidth,
          ).length,
        };
      });

      expect(collected.storyOrder).toEqual(stories);
      expect(collected.gridTracks).toEqual([
        expectedTracks(viewport),
        expectedTracks(viewport),
        expectedTracks(viewport),
        expectedTracks(viewport),
      ]);
      expect(collected.heroHeight).toBeGreaterThanOrEqual(
        Math.round(viewport.height * 0.7),
      );
      expect(collected.loadedImageCount).toBe(5);
      expect(collected.textOverflowCount).toBe(0);
      expect(collected.documentScrollWidth).toBeLessThanOrEqual(viewport.width);

      const screenshot = await page.screenshot({
        fullPage: true,
        path: join(outputDirectory, `${locale}-${viewport.name}.png`),
      });
      expect(screenshot.byteLength).toBeGreaterThan(50_000);
      metrics.push({
        ...collected,
        locale,
        screenshotBytes: screenshot.byteLength,
        viewport,
      });
    });
  }
}
