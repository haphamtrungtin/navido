import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { expect, test } from '@playwright/test';
import { format } from 'prettier';

type Locale = 'vi' | 'en' | 'ko';
type Viewport = Readonly<{ height: number; name: string; width: number }>;
type StoryPosition = Readonly<{
  imageAboveCopy: boolean;
  imageLeftOfCopy: boolean;
}>;
type Metrics = Readonly<{
  desktopHeaderMapsVisible: boolean;
  documentScrollWidth: number;
  mobileBarClearance: number | null;
  mobileBarVisible: boolean;
  gridTracks: number[];
  heroCropped: boolean;
  heroHeight: number;
  heroObjectFit: string;
  imageCount: number;
  loadedImageCount: number;
  locale: Locale;
  screenshotBytes: number;
  storyOrder: string[];
  storyPositions: StoryPosition[];
  textOverflowCount: number;
  viewport: Viewport;
}>;

const locales: readonly Locale[] = ['vi', 'en', 'ko'];
const viewports: readonly Viewport[] = [
  { height: 900, name: 'desktop-1440x900', width: 1440 },
  { height: 1024, name: 'tablet-768x1024', width: 768 },
  { height: 844, name: 'mobile-390x844', width: 390 },
];
const stories = [
  'morning-light',
  'quiet-table',
  'downstairs',
  'upstairs',
] as const;
const outputDirectory = join(
  process.cwd(),
  'artifacts',
  'visual-qa',
  'our-space',
);
const metrics: Metrics[] = [];

function expectedTracks(viewport: Viewport) {
  if (viewport.width >= 1024) return 12;
  if (viewport.width >= 768) return 8;
  return 1;
}

function storyComposition(metric: Metrics) {
  return metric.storyPositions
    .map((position) =>
      metric.viewport.width >= 768
        ? position.imageLeftOfCopy
          ? 'left'
          : 'right'
        : position.imageAboveCopy
          ? 'above'
          : 'below',
    )
    .join('/');
}

test.afterAll(async () => {
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(
    join(outputDirectory, 'metrics.json'),
    await format(`${JSON.stringify(metrics, null, 2)}\n`, {
      filepath: 'metrics.json',
    }),
  );
  await writeFile(
    join(outputDirectory, 'comparison.md'),
    await format(
      `# Our Space Visual QA

Generated by \`pnpm verify:our-space-visual\`. Desktop is compared to the Stitch editorial intent; tablet is a derived eight-column layout; mobile is the verified single-column reading order.

## Contracts

| Contract | Assertion |
| --- | --- |
| Hero | Morning interior image decodes, fills a tall editorial hero, uses \`object-fit: cover\`, and has a source ratio distinct from its frame |
| Stories | Four images appear in morning-light, quiet-table, downstairs, upstairs order; desktop/tablet alternate sides and mobile puts image before copy |
| Grids | 12 tracks desktop, derived 8 tracks tablet, one track mobile |
| Callout | One localized Visit link follows the stories |
| Shell | Shared header remains sticky while the page scrolls |
| Containment | Text and sections do not overflow horizontally |

## Measurements

| Locale | Viewport | Hero height | Hero crop | Grid tracks | Image/copy positions | Images decoded | Text overflow | Document width | Screenshot bytes |
| --- | --- | ---: | --- | --- | --- | --- | ---: | ---: | ---: |
${metrics
  .map(
    (metric) =>
      `| ${metric.locale} | ${metric.viewport.name} | ${metric.heroHeight}px | ${metric.heroObjectFit}/${metric.heroCropped ? 'cropped' : 'uncropped'} | ${metric.gridTracks.join('/')} | ${storyComposition(metric)} | ${metric.loadedImageCount}/${metric.imageCount} | ${metric.textOverflowCount} | ${metric.documentScrollWidth} | ${metric.screenshotBytes} |`,
  )
  .join('\n')}

## Comparison Notes

Desktop preserves the alternating image-and-copy editorial composition, verified from rendered image-frame and heading rectangles. Tablet reduces that composition to an eight-column derivative with the same alternation. Mobile stacks each image above its matching copy. The hero uses \`object-fit: cover\` and a source aspect ratio distinct from its rendered frame, which verifies visible cover cropping. No visual discrepancy was detected when this file was generated.
`,
      { filepath: 'comparison.md' },
    ),
  );
});

for (const locale of locales) {
  for (const viewport of viewports) {
    test(`verifies ${locale} Our Space at ${viewport.name}`, async ({
      page,
    }) => {
      await page.setViewportSize(viewport);
      const response = await page.goto(`/${locale}/our-space`, {
        waitUntil: 'networkidle',
      });

      expect(response?.status()).toBe(200);
      await expect(page.locator('h1')).toHaveCount(1);
      await expect(page.locator('[data-space-story]')).toHaveCount(4);
      await expect(page.locator('[data-space-callout]')).toHaveCount(1);
      await expect(
        page.locator(`[data-space-callout] a[href="/${locale}/visit"]`),
      ).toHaveCount(1);

      const images = page.locator('main img');
      await expect(images).toHaveCount(5);
      for (let index = 0; index < 5; index += 1) {
        const image = images.nth(index);
        await image.scrollIntoViewIfNeeded();
        await expect
          .poll(() =>
            image.evaluate((element) => {
              const htmlImage = element as HTMLImageElement;
              return htmlImage.complete && htmlImage.naturalWidth > 0;
            }),
          )
          .toBe(true);
      }

      await page.evaluate(() =>
        window.scrollTo({ top: 0, behavior: 'instant' }),
      );
      const headerTop = await page
        .locator('header')
        .evaluate((header) => Math.round(header.getBoundingClientRect().top));
      await page.evaluate(() =>
        window.scrollTo({ top: 480, behavior: 'instant' }),
      );
      expect(
        await page
          .locator('header')
          .evaluate((header) => Math.round(header.getBoundingClientRect().top)),
      ).toBe(headerTop);

      const collected = await page.evaluate(() => {
        const main = document.querySelector('main');
        const hero = main?.querySelector<HTMLElement>(
          '[data-space-section="hero"]',
        );
        const heroImage = hero?.querySelector<HTMLImageElement>(
          '[data-space-hero-image]',
        );
        const grids = Array.from(
          main?.querySelectorAll<HTMLElement>('[data-space-grid]') ?? [],
        );
        const textNodes = Array.from(
          main?.querySelectorAll<HTMLElement>('h1, h2, h3, p') ?? [],
        );
        const pageImages = Array.from(main?.querySelectorAll('img') ?? []);
        const storyPositions = Array.from(
          main?.querySelectorAll<HTMLElement>('[data-space-story]') ?? [],
        ).map((story) => {
          const image = story.querySelector<HTMLElement>(
            '[data-testid="editorial-image-frame"]',
          );
          const copy = story.querySelector<HTMLElement>('h2');
          const imageRect = image?.getBoundingClientRect();
          const copyRect = copy?.getBoundingClientRect();

          return {
            imageAboveCopy: Boolean(
              imageRect && copyRect && imageRect.bottom <= copyRect.top,
            ),
            imageLeftOfCopy: Boolean(
              imageRect && copyRect && imageRect.left < copyRect.left,
            ),
          };
        });

        const headerMaps = document
          .querySelector('header nav')
          ?.parentElement?.querySelector<HTMLAnchorElement>(
            'a[href*="google.com/maps/search"]',
          );
        const mobileBar = document.querySelector<HTMLElement>(
          '[data-testid="mobile-conversion-bar"]',
        );
        const footerLinks =
          document.querySelectorAll<HTMLAnchorElement>('footer a');
        const finalFooterLink = footerLinks.item(footerLinks.length - 1);
        const shell = {
          desktopHeaderMapsVisible: Boolean(
            headerMaps && headerMaps.getClientRects().length > 0,
          ),
          mobileBarClearance:
            mobileBar &&
            mobileBar.getClientRects().length > 0 &&
            finalFooterLink
              ? Math.floor(
                  mobileBar.getBoundingClientRect().top -
                    (finalFooterLink.getBoundingClientRect().bottom -
                      Math.max(
                        0,
                        document.documentElement.scrollHeight -
                          window.innerHeight,
                      )),
                )
              : null,
          mobileBarVisible: Boolean(
            mobileBar && mobileBar.getClientRects().length > 0,
          ),
        };

        return {
          ...shell,
          documentScrollWidth: document.documentElement.scrollWidth,
          gridTracks: grids.map((grid) => {
            const template = getComputedStyle(grid).gridTemplateColumns;
            return template === 'none'
              ? 0
              : template.trim().split(/\s+/).length;
          }),
          heroCropped: Boolean(
            hero &&
            heroImage &&
            Math.abs(
              heroImage.naturalWidth / heroImage.naturalHeight -
                hero.getBoundingClientRect().width /
                  hero.getBoundingClientRect().height,
            ) > 0.05,
          ),
          heroHeight: Math.round(hero?.getBoundingClientRect().height ?? 0),
          heroObjectFit: heroImage ? getComputedStyle(heroImage).objectFit : '',
          imageCount: pageImages.length,
          loadedImageCount: pageImages.filter(
            (image) => image.complete && image.naturalWidth > 0,
          ).length,
          storyOrder: Array.from(
            main?.querySelectorAll('[data-space-story]') ?? [],
          ).map((story) => story.getAttribute('data-space-story') ?? ''),
          storyPositions,
          textOverflowCount: textNodes.filter(
            (node) => node.scrollWidth > node.clientWidth,
          ).length,
        };
      });

      expect(collected.storyOrder).toEqual(stories);
      expect(collected.gridTracks).toEqual([
        expectedTracks(viewport),
        expectedTracks(viewport),
        expectedTracks(viewport),
        expectedTracks(viewport),
      ]);
      expect(collected.heroHeight).toBeGreaterThanOrEqual(
        Math.round(viewport.height * 0.7),
      );
      expect(collected.heroObjectFit).toBe('cover');
      expect(collected.heroCropped).toBe(true);
      if (viewport.width >= 768) {
        expect(
          collected.storyPositions.map((position) => position.imageLeftOfCopy),
        ).toEqual([true, false, true, false]);
      } else {
        expect(
          collected.storyPositions.map((position) => position.imageAboveCopy),
        ).toEqual([true, true, true, true]);
      }
      expect(collected.loadedImageCount).toBe(5);
      expect(collected.textOverflowCount).toBe(0);
      expect(collected.documentScrollWidth).toBeLessThanOrEqual(viewport.width);
      expect(collected.desktopHeaderMapsVisible).toBe(viewport.width >= 768);
      expect(collected.mobileBarVisible).toBe(viewport.width < 768);
      if (viewport.width < 768) {
        expect(collected.mobileBarClearance).toBeGreaterThanOrEqual(0);
      } else {
        expect(collected.mobileBarClearance).toBeNull();
      }

      await page.locator('nextjs-portal').evaluateAll((portals) => {
        portals.forEach((portal) => portal.remove());
      });
      await expect(page.locator('nextjs-portal')).toHaveCount(0);

      const screenshot = await page.screenshot({
        fullPage: true,
        path: join(outputDirectory, `${locale}-${viewport.name}.png`),
      });
      expect(screenshot.byteLength).toBeGreaterThan(50_000);
      metrics.push({
        ...collected,
        locale,
        screenshotBytes: screenshot.byteLength,
        viewport,
      });
    });
  }
}
