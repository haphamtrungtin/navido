import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

import { expect, test } from '@playwright/test';
import { format } from 'prettier';

type Locale = 'vi' | 'en' | 'ko';
type Viewport = Readonly<{ height: number; name: string; width: number }>;
type Bounds = Readonly<{
  bottom: number;
  height: number;
  left: number;
  right: number;
  top: number;
  width: number;
}>;
type Frame = Readonly<{
  bounds: Bounds;
  naturalRatio: number;
  objectFit: string;
  objectPosition: string;
  ratio: number;
}>;
type Metrics = Readonly<{
  action: Bounds;
  actionAnchorCount: number;
  captureScrollY: number;
  detailsBorderBottom: number;
  detailsBorderTop: number;
  desktopHeaderMapsVisible: boolean;
  documentScrollWidth: number;
  footerPresent: boolean;
  mobileBarClearance: number | null;
  mobileBarVisible: boolean;
  information: Bounds;
  intro: { copy: Bounds; exterior: Frame };
  loadedImageCount: number;
  map: Frame;
  mapIsLinked: boolean;
  pendingCount: number;
  screenshotBytes: number;
  stickyHeader: boolean;
  textOverflowCount: number;
  viewport: Viewport;
}>;

const locales: readonly Locale[] = ['vi', 'en', 'ko'];
const viewports: readonly Viewport[] = [
  { height: 900, name: 'desktop-1440x900', width: 1440 },
  { height: 1024, name: 'tablet-768x1024', width: 768 },
  { height: 844, name: 'mobile-390x844', width: 390 },
];
const approvedImageUrls = [
  '/images/stitch/visit-exterior.jpg',
  '/images/stitch/visit-map-placeholder.jpg',
] as const;
const outputDirectory = join(process.cwd(), 'artifacts', 'visual-qa', 'visit');
const metrics: Metrics[] = [];

const geometryContracts: Record<
  Viewport['name'],
  Readonly<{
    action: Pick<Bounds, 'left' | 'width'>;
    exterior: Pick<Bounds, 'height' | 'left' | 'width'>;
    information: Pick<Bounds, 'left' | 'width'>;
    introCopy: Pick<Bounds, 'left' | 'width'>;
    map: Pick<Bounds, 'height' | 'left' | 'width'>;
  }>
> = {
  'desktop-1440x900': {
    action: { left: 644, width: 352 },
    exterior: { height: 311, left: 744, width: 552 },
    information: { left: 244, width: 352 },
    introCopy: { left: 244, width: 352 },
    map: { height: 202, left: 1044, width: 252 },
  },
  'tablet-768x1024': {
    action: { left: 400, width: 344 },
    exterior: { height: 246, left: 306, width: 438 },
    information: { left: 24, width: 344 },
    introCopy: { left: 24, width: 250 },
    map: { height: 576, left: 24, width: 720 },
  },
  'mobile-390x844': {
    action: { left: 20, width: 350 },
    exterior: { height: 197, left: 20, width: 350 },
    information: { left: 20, width: 350 },
    introCopy: { left: 20, width: 350 },
    map: { height: 280, left: 20, width: 350 },
  },
};

function expectNear(actual: number, expected: number, tolerance: number) {
  expect(Math.abs(actual - expected)).toBeLessThanOrEqual(tolerance);
}

test.afterAll(async () => {
  await mkdir(outputDirectory, { recursive: true });
  await writeFile(
    join(outputDirectory, 'metrics.json'),
    await format(`${JSON.stringify(metrics, null, 2)}\n`, {
      filepath: 'metrics.json',
    }),
  );
  await writeFile(
    join(outputDirectory, 'comparison.md'),
    await format(
      `# Visit Visual QA

Generated by \`pnpm verify:visit-visual\`. Desktop is compared against the Stitch editorial intent. Tablet is an explicitly derived eight-column arrangement, while mobile verifies the information, actions, then non-interactive map reading order.

## Contracts

| Contract | Assertion |
| --- | --- |
| Sources and crops | The exterior then map placeholder use the exact two approved local URLs, decode successfully, fill independent frame contracts, and use centered cover rendering. |
| Desktop composition | The title/exterior introduction uses the editorial asymmetric 12-column arrangement. Information and actions occupy balanced four-column positions, with the map in the remaining three columns. |
| Derived layouts | Tablet derives to two four-column information/action columns with a full-width map; mobile stacks information, actions, then map. |
| Pending safety | Eight semantically identified localized pending states render in exact address, hours, phone, directions, Grab, Instagram, Facebook, and map order, with no telephone, Maps, Grab, Instagram, Facebook, or disabled placeholder action. |
| Shell and containment | The shared header remains sticky, footer is present, section rules are visible, captures begin at scroll zero, and no text or document width overflows. |

## Measurements

| Viewport | Information | Actions | Exterior | Map | Pending | Header sticky | Screenshot bytes |
| --- | --- | --- | --- | --- | ---: | --- | ---: |
${metrics
  .map(
    (metric) =>
      `| ${metric.viewport.name} | ${metric.information.left}/${metric.information.width} | ${metric.action.left}/${metric.action.width} | ${metric.intro.exterior.bounds.left}/${metric.intro.exterior.bounds.width}x${metric.intro.exterior.bounds.height} | ${metric.map.bounds.left}/${metric.map.bounds.width}x${metric.map.bounds.height} | ${metric.pendingCount} | ${metric.stickyHeader} | ${metric.screenshotBytes} |`,
  )
  .join('\n')}

## Comparison Notes

The geometry contracts are fixed measurements from the intended 1200px container, 24px/20px gutters, 12/8/1-column breakpoints, and 48px/32px grid gaps. They are not calculated from the live layout. Exterior and map source aspect ratios are intentionally distinct from their frames, proving cover crops. Desktop retains editorial asymmetry; tablet is a derived layout; mobile preserves the semantic stack. Every screenshot is captured from scroll position zero.
`,
      { filepath: 'comparison.md' },
    ),
  );
});

for (const locale of locales) {
  for (const viewport of viewports) {
    test(`verifies ${locale} Visit at ${viewport.name}`, async ({ page }) => {
      await page.setViewportSize(viewport);
      const response = await page.goto(`/${locale}/visit`, {
        waitUntil: 'networkidle',
      });

      expect(response?.status()).toBe(200);
      await expect(page.locator('html')).toHaveAttribute('lang', locale);
      await expect(page.locator('h1')).toHaveCount(1);

      const images = page.locator('main img');
      await expect(images).toHaveCount(2);
      for (const image of await images.all()) {
        await image.scrollIntoViewIfNeeded();
        await expect
          .poll(() =>
            image.evaluate((element) => {
              const nativeImage = element as HTMLImageElement;
              return nativeImage.complete && nativeImage.naturalWidth > 0;
            }),
          )
          .toBe(true);
      }

      await page.evaluate(() =>
        window.scrollTo({ top: 0, behavior: 'instant' }),
      );
      const headerTop = await page
        .locator('header')
        .evaluate((header) => Math.round(header.getBoundingClientRect().top));
      await page.evaluate(() =>
        window.scrollTo({ top: 480, behavior: 'instant' }),
      );
      expect(
        await page
          .locator('header')
          .evaluate((header) => Math.round(header.getBoundingClientRect().top)),
      ).toBe(headerTop);
      await page.evaluate(() =>
        window.scrollTo({ top: 0, behavior: 'instant' }),
      );
      await expect
        .poll(() => page.evaluate(() => Math.round(window.scrollY)))
        .toBe(0);

      const collected = await page.evaluate(() => {
        const toBounds = (rect: DOMRect): Bounds => ({
          bottom: Math.round(rect.bottom),
          height: Math.round(rect.height),
          left: Math.round(rect.left),
          right: Math.round(rect.right),
          top: Math.round(rect.top),
          width: Math.round(rect.width),
        });
        const toFrame = (frame: HTMLElement | null): Frame => {
          const image = frame?.querySelector('img');
          const bounds = toBounds(
            frame?.getBoundingClientRect() ?? new DOMRect(),
          );

          return {
            bounds,
            naturalRatio:
              image && image.naturalHeight > 0
                ? image.naturalWidth / image.naturalHeight
                : 0,
            objectFit: image ? getComputedStyle(image).objectFit : '',
            objectPosition: image ? getComputedStyle(image).objectPosition : '',
            ratio: bounds.height > 0 ? bounds.width / bounds.height : 0,
          };
        };
        const main = document.querySelector('main');
        const introduction = main?.querySelector<HTMLElement>(
          '[data-visit-section="introduction"]',
        );
        const details = main?.querySelector<HTMLElement>(
          '[data-visit-section="details"]',
        );
        const information = main?.querySelector<HTMLElement>(
          '[data-visit-section="information"]',
        );
        const actions = main?.querySelector<HTMLElement>(
          '[data-visit-section="actions"]',
        );
        const map = main?.querySelector<HTMLElement>(
          '[data-visit-section="map"]',
        );
        const frames = Array.from(
          main?.querySelectorAll<HTMLElement>(
            '[data-testid="editorial-image-frame"]',
          ) ?? [],
        );
        const imageUrls = Array.from(main?.querySelectorAll('img') ?? []).map(
          (image) => {
            const url = new URL(
              image.currentSrc || image.src,
              window.location.href,
            );
            return url.searchParams.get('url') ?? url.pathname;
          },
        );
        const textNodes = Array.from(
          main?.querySelectorAll<HTMLElement>(
            'h1, h2, h3, p, dt, dd, figcaption',
          ) ?? [],
        );
        const anchors = Array.from(main?.querySelectorAll('a') ?? []);

        const headerMaps = document
          .querySelector('header nav')
          ?.parentElement?.querySelector<HTMLAnchorElement>(
            'a[href*="google.com/maps/search"]',
          );
        const mobileBar = document.querySelector<HTMLElement>(
          '[data-testid="mobile-conversion-bar"]',
        );
        const footerLinks =
          document.querySelectorAll<HTMLAnchorElement>('footer a');
        const finalFooterLink = footerLinks.item(footerLinks.length - 1);
        const shell = {
          desktopHeaderMapsVisible: Boolean(
            headerMaps && headerMaps.getClientRects().length > 0,
          ),
          mobileBarClearance:
            mobileBar && finalFooterLink
              ? Math.floor(
                  mobileBar.getBoundingClientRect().top -
                    (finalFooterLink.getBoundingClientRect().bottom -
                      Math.max(
                        0,
                        document.documentElement.scrollHeight -
                          window.innerHeight,
                      )),
                )
              : null,
          mobileBarVisible: Boolean(
            mobileBar && mobileBar.getClientRects().length > 0,
          ),
        };

        return {
          ...shell,
          action: toBounds(actions?.getBoundingClientRect() ?? new DOMRect()),
          actionAnchorCount: anchors.length,
          captureScrollY: Math.round(window.scrollY),
          detailsBorderBottom: Math.round(
            parseFloat(
              getComputedStyle(details ?? document.body).borderBottomWidth,
            ),
          ),
          detailsBorderTop: Math.round(
            parseFloat(
              getComputedStyle(details ?? document.body).borderTopWidth,
            ),
          ),
          documentScrollWidth: document.documentElement.scrollWidth,
          footerPresent: Boolean(document.querySelector('footer')),
          information: toBounds(
            information?.getBoundingClientRect() ?? new DOMRect(),
          ),
          intro: {
            copy: toBounds(
              introduction
                ?.querySelector('h1')
                ?.parentElement?.getBoundingClientRect() ?? new DOMRect(),
            ),
            exterior: toFrame(frames[0] ?? null),
          },
          loadedImageCount: Array.from(
            main?.querySelectorAll('img') ?? [],
          ).filter((image) => image.complete && image.naturalWidth > 0).length,
          map: toFrame(frames[1] ?? null),
          mapIsLinked: Boolean(map?.querySelector('a')),
          pendingCount:
            main?.querySelectorAll('[data-visit-pending]').length ?? 0,
          textOverflowCount: textNodes.filter(
            (node) => node.scrollWidth > node.clientWidth,
          ).length,
          disabledActionCount:
            main?.querySelectorAll('[disabled], [aria-disabled="true"]')
              .length ?? 0,
          imageUrls,
          sectionOrder: [information, actions, map].map(
            (section) => section?.dataset.visitSection ?? '',
          ),
          stickyHeader:
            Math.round(
              document.querySelector('header')?.getBoundingClientRect().top ??
                Number.NaN,
            ) === 0,
        };
      });
      const contract = geometryContracts[viewport.name];
      const tolerance = viewport.width < 768 ? 2 : 3;

      if (!contract) {
        throw new Error(`Missing viewport contract for ${viewport.name}`);
      }

      expect(collected.captureScrollY).toBe(0);
      expect(collected.imageUrls).toEqual(approvedImageUrls);
      expect(collected.loadedImageCount).toBe(2);
      expect(collected.pendingCount).toBe(0);
      expect(collected.actionAnchorCount).toBe(7);
      expect(collected.disabledActionCount).toBe(0);
      expect(collected.mapIsLinked).toBe(true);
      expect(collected.footerPresent).toBe(true);
      expect(collected.stickyHeader).toBe(true);
      expect(collected.detailsBorderTop).toBeGreaterThanOrEqual(1);
      expect(collected.detailsBorderBottom).toBeGreaterThanOrEqual(1);
      expect(collected.textOverflowCount).toBe(0);
      expect(collected.documentScrollWidth).toBeLessThanOrEqual(viewport.width);
      expect(collected.desktopHeaderMapsVisible).toBe(viewport.width >= 768);
      expect(collected.mobileBarVisible).toBe(viewport.width < 768);
      if (viewport.width < 768) {
        expect(collected.mobileBarClearance).toBeGreaterThanOrEqual(0);
      } else {
        expect(collected.mobileBarClearance).toBeNull();
      }
      expect(collected.sectionOrder).toEqual(['information', 'actions', 'map']);

      expectNear(collected.intro.copy.left, contract.introCopy.left, tolerance);
      expectNear(
        collected.intro.copy.width,
        contract.introCopy.width,
        tolerance,
      );
      expectNear(
        collected.intro.exterior.bounds.left,
        contract.exterior.left,
        tolerance,
      );
      expectNear(
        collected.intro.exterior.bounds.width,
        contract.exterior.width,
        tolerance,
      );
      expectNear(
        collected.intro.exterior.bounds.height,
        contract.exterior.height,
        tolerance,
      );
      expectNear(collected.intro.exterior.ratio, 16 / 9, 0.02);
      expect(collected.intro.exterior.objectFit).toBe('cover');
      expect(collected.intro.exterior.objectPosition).toBe('50% 50%');
      expect(
        Math.abs(
          collected.intro.exterior.ratio -
            collected.intro.exterior.naturalRatio,
        ),
      ).toBeGreaterThan(0.05);

      expectNear(
        collected.information.left,
        contract.information.left,
        tolerance,
      );
      expectNear(
        collected.information.width,
        contract.information.width,
        tolerance,
      );
      expectNear(collected.action.left, contract.action.left, tolerance);
      expectNear(collected.action.width, contract.action.width, tolerance);
      expectNear(collected.map.bounds.left, contract.map.left, tolerance);
      expectNear(collected.map.bounds.width, contract.map.width, tolerance);
      expectNear(collected.map.bounds.height, contract.map.height, tolerance);
      expectNear(collected.map.ratio, 5 / 4, 0.02);
      expect(collected.map.objectFit).toBe('cover');
      expect(collected.map.objectPosition).toBe('50% 50%');
      expect(
        Math.abs(collected.map.ratio - collected.map.naturalRatio),
      ).toBeGreaterThan(0.05);

      if (viewport.width >= 768) {
        expect(collected.information.top).toBe(collected.action.top);
      } else {
        expect(collected.information.bottom).toBeLessThanOrEqual(
          collected.action.top,
        );
        expect(collected.action.bottom).toBeLessThanOrEqual(
          collected.map.bounds.top,
        );
      }

      const screenshot = await page.screenshot({
        fullPage: true,
        path: join(outputDirectory, `${locale}-${viewport.name}.png`),
      });
      expect(screenshot.byteLength).toBeGreaterThan(50_000);
      metrics.push({
        ...collected,
        screenshotBytes: screenshot.byteLength,
        viewport,
      });
    });
  }
}
